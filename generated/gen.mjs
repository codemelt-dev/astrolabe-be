// Prints api.ts, the TypeScript types of the explorer API (schema api), for
// @supabase/postgrest-js. Run it against a database with psql/api.sql
// applied (README.md): `DATABASE_URL=… npm run gen`.
//
// postgrest-typegen does the introspection and the generation; this script
// adjusts its metadata for this API before generating:
// - Columns and function results of the api_types domains (hex, base64,
//   int64, amount) are strings in JSON, through the domains' casts to json;
//   postgrest-typegen would type them by their base types (int64 as number),
//   or not at all.
// - View columns are nullable as far as Postgres knows. A column is made
//   non-null when it is a NOT NULL column of the same name in a table the view
//   reads, unless that table is the outer side of a join. Anything else stays
//   nullable, so the rule can only miss a non-null, never invent one.
// - The API is read-only: views get no Insert/Update types.
// - The views' row types are named without their schema ("trustlines", not
//   "api.trustlines"), as postgrest-js expects for embedded functions
//   (accounts?select=*,trustlines(*)); postgrest-typegen qualifies them
//   outside the public schema.
import pg from 'pg'
import { introspect } from '@supabase/postgrest-typegen/introspection'
import { generateTypescript, sortGeneratorMetadata } from '@supabase/postgrest-typegen/generation'

const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL })
const meta = await introspect(pool, { includedSchemas: ['api'] })

// [view, column] of every view column whose type is an api_types domain.
const domains = await pool.query(`
  SELECT c.relname AS view, a.attname AS column
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'api'
  JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
  JOIN pg_type t ON t.oid = a.atttypid
  JOIN pg_namespace tn ON tn.oid = t.typnamespace AND tn.nspname = 'api_types'
  WHERE c.relkind = 'v'`)

// [view, column] of every view column that is a NOT NULL column of a table
// the view reads, minus tables on the outer side of a join (and views with a
// RIGHT or FULL join, whose nullability this rule can't see).
const notNull = await pool.query(`
  WITH used AS (
    SELECT DISTINCT v.oid AS view, v.relname AS view_name, d.refobjid AS tbl, a.attname, a.attnotnull
    FROM pg_class v
    JOIN pg_namespace n ON n.oid = v.relnamespace AND n.nspname = 'api'
    JOIN pg_rewrite r ON r.ev_class = v.oid
    JOIN pg_depend d ON d.classid = 'pg_rewrite'::regclass AND d.objid = r.oid
                    AND d.refclassid = 'pg_class'::regclass AND d.refobjsubid > 0 AND d.refobjid <> v.oid
    JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
    WHERE v.relkind = 'v' AND pg_get_viewdef(v.oid) !~ '(RIGHT|FULL) JOIN'
  )
  SELECT u.view_name AS view, va.attname AS column
  FROM used u
  JOIN pg_attribute va ON va.attrelid = u.view AND va.attname = u.attname AND va.attnum > 0
  WHERE u.attnotnull
    AND pg_get_viewdef(u.view) !~ ('LEFT JOIN ' || u.tbl::regclass::text || ' ')
  GROUP BY 1, 2`)
await pool.end()

const key = (view, column) => `${view}.${column}`
const strings = new Set(domains.rows.map(r => key(r.view, r.column)))
const required = new Set(notNull.rows.map(r => key(r.view, r.column)))
for (const c of meta.columns) {
  if (strings.has(key(c.table, c.name))) {
    c.format = 'text'
    c.data_type = 'text'
  }
  if (required.has(key(c.table, c.name))) c.is_nullable = false
  c.is_updatable = false
}
for (const t of meta.types) {
  if (t.schema === 'api' && t.format === `api.${t.name}`) t.format = t.name
  // Function results of the domains (rpc/order_book's price and amount) are
  // strings too; view columns get theirs above.
  if (t.schema === 'api_types') t.name = t.format = 'text'
}
for (const v of meta.views) {
  v.is_updatable = false
  v.is_insert_enabled = false
  v.is_update_enabled = false
}

process.stdout.write('// Code generated by generated/gen.mjs from the api schema (psql/api.sql). DO NOT EDIT.\n\n' + await generateTypescript(sortGeneratorMetadata(meta), { defaultSchema: 'api', postgrestVersion: '14' }))
